import Link from "next/link";
import { getGuides } from "@/lib/data";
import { DIFFICULTY, approvalWait, evidenceCounts, minutes } from "@/lib/format";
import AskBox from "./ask-box";

export const dynamic = "force-dynamic";

export default async function Home() {
  const guides = await getGuides();
  const library = guides.filter((g) => g.inLibrary);
  const generated = guides.filter((g) => !g.inLibrary);
  return (
    <main>
      <section className="hero">
        <h1>How long until your agent&apos;s users can connect this app?</h1>
        <p>
          Before your users can authorize an app, you often need your own OAuth app with the provider, and sometimes its approval.
          Each guide shows the hands-on setup time, any approval wait, the requirements that trip people up, and the evidence behind
          every claim.
        </p>
        <AskBox />
      </section>

      <h2 className="section-title">Library</h2>
      <div className="grid">{library.map((g) => <GuideCard key={g.slug} g={g} />)}</div>

      {generated.length > 0 && (
        <>
          <h2 className="section-title">Generated by visitors</h2>
          <div className="grid">{generated.map((g) => <GuideCard key={g.slug} g={g} />)}</div>
        </>
      )}
    </main>
  );
}

function GuideCard({ g }: { g: Awaited<ReturnType<typeof getGuides>>[number] }) {
  const x = g.guide!;
  const d = x.verdict.difficulty;
  const ev = evidenceCounts(x);
  return (
    <Link href={`/guides/${g.slug}`} className="card">
      <div className="card-head">
        <h3>{x.app.name}</h3>
        <span className={`pill d-${d}`}>{DIFFICULTY[d].label}</span>
      </div>
      <p>{x.verdict.headline}</p>
      <div className="times">
        <div><span>Setup</span><b>{minutes(x.verdict.setup_minutes)}</b></div>
        <div><span>Approval wait</span><b>{approvalWait(x.verdict.approval)}</b></div>
      </div>
      <div className="evline">
        <span><i className="dot e-verified_live" />{ev.verified_live} verified live</span>
        <span><i className="dot e-documented" />{ev.documented} documented</span>
        <span><i className="dot e-inferred" />{ev.inferred} inferred</span>
      </div>
    </Link>
  );
}
